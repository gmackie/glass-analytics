/**
 * Generates packages/core/src/raster/font.ts: a glyph atlas of Inter (SIL Open Font License
 * 1.1) at the two sizes report charts use, so the Worker can draw text into PNGs with no
 * font engine. Inter comes from @fontsource/inter at a pinned version; Chromium (Playwright,
 * already a dev dependency) rasterises each glyph, and its coverage is stored at 4 bits.
 *
 *   node scripts/raster-font.ts
 */

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const FONT =
  'https://cdn.jsdelivr.net/npm/@fontsource/inter@5.1.0/files/inter-latin-500-normal.woff2';
const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'packages',
  'core',
  'src',
  'raster',
  'font.ts',
);
const SIZES = [11, 13];
const CHARS = [
  ...Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)),
  ...'▲▼–—·…€£→×’“”',
].join('');

interface SizeOut {
  size: number;
  height: number;
  ascent: number;
  /** char → [advance, x offset into the strip, cell width] */
  glyphs: Record<string, [number, number, number]>;
  /** Strip width; the strip is `height` rows of 4-bit coverage, two pixels per byte. */
  width: number;
  /** Base64, in short chunks (long runs of "A" would look like API tokens to secret scanners). */
  data: string[];
}

const res = await fetch(FONT);
if (!res.ok) throw new Error(`Font download failed: ${res.status}`);
const font = Buffer.from(await res.arrayBuffer()).toString('base64');

const browser = await chromium.launch();
const page = await browser.newPage({ deviceScaleFactor: 1 });
const sizes = (await page.evaluate(
  async ({ font, sizes, chars }) => {
    const face = new FontFace('Atlas', `url(data:font/woff2;base64,${font})`);
    await face.load();
    document.fonts.add(face);
    const out = [];
    for (const size of sizes) {
      const canvas = document.createElement('canvas');
      const ctx = canvas.getContext('2d', { willReadFrequently: true })!;
      ctx.font = `500 ${size}px Atlas`;
      const height = Math.ceil(size * 1.3);
      const ascent = Math.round(size * 0.97);
      const cells = [...chars].map((c) => {
        const advance = ctx.measureText(c).width;
        return { c, advance, width: Math.max(1, Math.ceil(advance) + 1) };
      });
      const width = cells.reduce((sum, x) => sum + x.width, 0);
      canvas.width = width;
      canvas.height = height;
      ctx.font = `500 ${size}px Atlas`;
      ctx.fillStyle = '#000';
      ctx.textBaseline = 'alphabetic';
      const glyphs: Record<string, [number, number, number]> = {};
      let x = 0;
      for (const cell of cells) {
        ctx.fillText(cell.c, x, ascent);
        glyphs[cell.c] = [Math.round(cell.advance * 100) / 100, x, cell.width];
        x += cell.width;
      }
      const alpha = ctx.getImageData(0, 0, width, height).data;
      const bytes = new Uint8Array(Math.ceil((width * height) / 2));
      for (let i = 0; i < width * height; i++) {
        const level = Math.round(alpha[i * 4 + 3]! / 17);
        bytes[i >> 1]! |= i & 1 ? level : level << 4;
      }
      let bin = '';
      for (const b of bytes) bin += String.fromCharCode(b);
      const b64 = btoa(bin);
      const data: string[] = [];
      for (let i = 0; i < b64.length; i += 48) data.push(b64.slice(i, i + 48));
      out.push({ size, height, ascent, glyphs, width, data });
    }
    return out;
  },
  { font, sizes: SIZES, chars: CHARS },
)) as SizeOut[];
await browser.close();

const body = sizes.map((s) => `  ${s.size}: ${JSON.stringify(s)},`).join('\n');
writeFileSync(
  OUT,
  `/**
 * Generated by scripts/raster-font.ts: do not edit. Inter 5.1.0 (SIL Open Font License 1.1,
 * https://github.com/rsms/inter) at ${SIZES.join(' and ')} px, weight 500, 4-bit coverage.
 */

export interface AtlasSize {
  size: number;
  height: number;
  ascent: number;
  glyphs: Record<string, [number, number, number]>;
  width: number;
  /** Base64 in short chunks, so no long run of "A" looks like a token to secret scanners. */
  data: string[];
}

export const ATLAS: Record<number, AtlasSize> = {
${body}
};
`,
);
console.log(`Wrote ${OUT} (${sizes.map((s) => `${s.size}px: ${s.width}×${s.height}`).join(', ')})`);
